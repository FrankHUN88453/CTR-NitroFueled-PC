"""Generate src/gen/nid_names.inc: {"nid", "name"} for every import/export used by
the game modules (for readable logs).

usage: python gen_nid_names.py <out_dir_with_dyn_json> <out.inc>
"""
import glob
import json
import os
import sys


def main(dyn_dir, out_path):
    names = {}
    for p in glob.glob(os.path.join(dyn_dir, "*.dyn.json")):
        d = json.load(open(p))
        for i in d["imports"] + d["data_imports"]:
            if i.get("nid") and i.get("name"):
                names[i["nid"]] = i["name"]
        for e in d["exports"]:
            if e.get("nid") and e.get("name"):
                names[e["nid"]] = e["name"]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="ascii") as f:
        f.write("// generated by tools/gen_nid_names.py\n")
        for nid, name in sorted(names.items()):
            f.write(f'{{"{nid}", "{name}"}},\n')
    print(f"{len(names)} names -> {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
