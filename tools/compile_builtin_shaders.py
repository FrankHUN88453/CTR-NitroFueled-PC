"""Compiles the renderer's built-in shaders (port/src/gfx/builtin.hlsl) to DXBC and writes them as C
arrays to port/src/gfx/builtin_shaders.inc, so that no build or run needs a shader compiler (Linux
builds have none). Run it on Windows after changing builtin.hlsl.

usage: python compile_builtin_shaders.py
"""
import ctypes
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "port", "src", "gfx", "builtin.hlsl")
OUT = os.path.join(HERE, "..", "port", "src", "gfx", "builtin_shaders.inc")
ENTRIES = [("kBuiltinBlitVs", "vsmain", "vs_5_0"), ("kBuiltinBlitPs", "psmain", "ps_5_0"),
           ("kBuiltinCopyPs", "copyps", "ps_5_0")]


def compile_hlsl(src, entry, target):
    d3dc = ctypes.WinDLL("d3dcompiler_47.dll")
    d3dc.D3DCompile.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_void_p,
                                ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                                ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    code, err = ctypes.c_void_p(), ctypes.c_void_p()
    b = src.encode()
    hr = d3dc.D3DCompile(b, len(b), b"builtin", None, None, entry.encode(), target.encode(), 0, 0,
                         ctypes.byref(code), ctypes.byref(err))

    def blob(p):
        if not p.value:
            return b""
        vt = ctypes.cast(p, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
        data = ctypes.string_at(ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vt[3])(p),
                                ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vt[4])(p))
        ctypes.WINFUNCTYPE(ctypes.c_ulong, ctypes.c_void_p)(vt[2])(p)
        return data

    if hr & 0x80000000:
        raise SystemExit(f"{entry}: {blob(err).decode(errors='replace')}")
    return blob(code)


def main():
    src = open(SRC, encoding="utf-8").read()
    out = ["// Generated by tools/compile_builtin_shaders.py from builtin.hlsl - do not edit.", ""]
    for name, entry, target in ENTRIES:
        data = compile_hlsl(src, entry, target)
        out.append(f"// {entry} ({target}), {len(data)} bytes")
        out.append(f"const unsigned char {name}[] = {{")
        for i in range(0, len(data), 20):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
        out.append("};")
        out.append("")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"{len(ENTRIES)} shaders -> {OUT}")


if __name__ == "__main__":
    main()
